"""Reading the bot templates under ``templates/bots/``.

A template is a folder of plain files describing one role: its profile, the
facts it starts out knowing, its skills, its routines, and the first
conversation it has with a new owner. ``share.json`` next to them is the same
thing as one payload, generated by ``scripts/build_bot_templates.py``.

This module only ever **reads**. Writing a template is the build script's job,
so there is one writer and no chance of the command line and the script
disagreeing about the format.
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from pathlib import Path

from .config import repo_root
from .errors import JobpilotError

TEMPLATES_DIR = "templates"
BOTS_DIR = "bots"


def templates_root() -> Path:
    return repo_root() / TEMPLATES_DIR / BOTS_DIR


@dataclass(frozen=True, slots=True)
class BotTemplate:
    """One role, as the files describe it."""

    role: str
    directory: Path
    payload: dict

    @property
    def name(self) -> str:
        return str(self.payload.get("name", self.role))

    @property
    def title(self) -> str:
        return str(self.payload.get("title", ""))

    @property
    def description(self) -> str:
        return " ".join(str(self.payload.get("description", "")).split())

    @property
    def skills(self) -> list[dict]:
        return [s for s in self.payload.get("skills", []) if isinstance(s, dict)]

    @property
    def routines(self) -> list[dict]:
        return [r for r in self.payload.get("routines", []) if isinstance(r, dict)]

    @property
    def memories(self) -> list[str]:
        return [str(m) for m in self.payload.get("memories", [])]

    @property
    def plugins(self) -> list[str]:
        return [str(p) for p in self.payload.get("plugins", [])]

    @property
    def talks_to_owner(self) -> bool:
        """Only the Lead does. Everyone else reports to it."""
        return self.role == "lead"

    def share_json(self) -> str:
        return json.dumps(self.payload, indent=2, ensure_ascii=True)

    def words(self) -> str:
        """What this role is, in the plain words the files already use."""
        lines = [f"{self.name} ({self.title})", "", self.description, ""]
        lines.append(
            "Talks to you directly."
            if self.talks_to_owner
            else "Reports to the lead, never to you directly."
        )
        if self.plugins:
            lines.append("Needs connecting to: " + ", ".join(self.plugins) + ".")
        lines.append("")
        lines.append(f"What it knows to start with: {len(self.memories)} facts.")
        lines.append("What it can do:")
        for skill in self.skills:
            lines.append(f"  - {skill['name']}: {skill['description']}")
        lines.append("What it does by itself:")
        for routine in self.routines:
            when = routine.get("human") or routine.get("schedule", "")
            off = "" if routine.get("enabled", True) else " (switched off)"
            lines.append(f"  - {when}: {routine['name']}{off}")
        return "\n".join(lines)


def roles() -> list[str]:
    root = templates_root()
    if not root.exists():
        return []
    return sorted(path.name for path in root.glob("*") if (path / "share.json").exists())


def load(role: str) -> BotTemplate:
    directory = templates_root() / role
    payload_path = directory / "share.json"
    if not payload_path.exists():
        known = ", ".join(roles()) or "none"
        raise JobpilotError(
            f"I do not have a template called {role!r}.",
            hint=f"The ones I have are: {known}.",
        )
    try:
        payload = json.loads(payload_path.read_text(encoding="utf-8"))
    except ValueError as exc:
        raise JobpilotError(
            f"The template for {role!r} is not readable.",
            hint=f"Run scripts/build_bot_templates.py to rebuild it. ({exc})",
        ) from exc
    return BotTemplate(role=role, directory=directory, payload=payload)


def load_all() -> list[BotTemplate]:
    return [load(role) for role in roles()]


def summary() -> str:
    """One line per role, the lead first because it is the one you talk to."""
    found = load_all()
    if not found:
        return "I have no bot templates to show you."
    found.sort(key=lambda t: (not t.talks_to_owner, t.role))
    lines = ["The team, one template each:", ""]
    for template in found:
        who = "talks to you" if template.talks_to_owner else "reports to the lead"
        lines.append(f"  {template.role:<10} {template.name} - {who}")
    lines.append("")
    lines.append("'jobpilot templates show <role>' says what one of them does.")
    return "\n".join(lines)
